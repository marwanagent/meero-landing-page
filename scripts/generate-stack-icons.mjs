import * as icons from "simple-icons";
import { writeFile } from "node:fs/promises";

const brands = {
  "google-calendar": "siGooglecalendar",
  gmail: "siGmail",
  "google-drive": "siGoogledrive",
  "google-sheets": "siGooglesheets",
  slack: "siSlack",
  stripe: "siStripe",
  quickbooks: "siQuickbooks",
  hubspot: "siHubspot",
  calendly: "siCalendly",
  notion: "siNotion",
  airtable: "siAirtable",
  zoom: "siZoom",
};

const paths = {};
for (const [slug, exportName] of Object.entries(brands)) {
  const icon = icons[exportName];
  if (!icon) {
    console.warn(`${slug}: unavailable in simple-icons, retaining text fallback`);
    continue;
  }
  paths[slug] = { path: icon.path, title: icon.title };
}

await writeFile(
  new URL("../src/components/sections/stackIcons.ts", import.meta.url),
  `// Generated by scripts/generate-stack-icons.mjs.\n` +
    `export const stackIcons: Record<string, { path: string; title: string } | undefined> = ${JSON.stringify(paths, null, 2)};\n`,
);
